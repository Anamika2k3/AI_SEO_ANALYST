const buildKeywords = () => {
  const items: Keyword[] = [];
  const suffixes = ["guide", "report", "news", "statistics", "strategy", "analysis", "trends", "forecast"];
  for (let index = 0; index < 50; index += 1) {
    const trend = trendSeeds[index % trendSeeds.length];
    items.push({
      id: `kw-${index + 1}`,
      keyword: `${trend.title} ${suffixes[index % suffixes.length]}`,
      industry: trend.industry,
      category: trend.category,
      intent: ["INFORMATIONAL", "COMMERCIAL", "TRANSACTIONAL", "NAVIGATIONAL"][index % 4] as Keyword["intent"],
      search_volume: 2500 + index * 137,
      difficulty: 20 + (index * 3) % 60,
      freshness: 90 - (index % 25),
      cluster: `${trend.category}-cluster-${(index % 5) + 1}`,
    });
  }
  return items;
};


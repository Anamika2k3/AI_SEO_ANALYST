export const getDemoDataForIndustry = (industry: IndustryId | string) => {
  const normalized = getIndustryConfig(industry).id;
  return {
    trends: DEMO_DATA.trends.filter((trend) => trend.industry === normalized || normalized === "other"),
    keywords: DEMO_DATA.keywords.filter((keyword) => keyword.industry === normalized || normalized === "other"),
    newsArticles: DEMO_DATA.newsArticles.filter((article) => article.industry === normalized || normalized === "other"),
    competitors: DEMO_DATA.competitors.filter((competitor) => competitor.industry === normalized || normalized === "other"),
    publications: DEMO_DATA.publications.filter((publication) => publication.industry === normalized || normalized === "other"),
    campaigns: DEMO_DATA.campaigns.filter((campaign) => campaign.industry === normalized || normalized === "other"),
  };
};
